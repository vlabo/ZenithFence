//! Generates per-component Markdown item references under `docs/LLMs/`,
//! optimized for LLM consumption: one section per Rust source file listing every
//! item (constants, macros, types with their full definitions, impl blocks,
//! functions, extern blocks) with its doc comment and signature, but without
//! function bodies. Test code (`#[test]`, `#[cfg(test)]`) is skipped.
//!
//! Private items are included on purpose: most of the interesting logic in the
//! driver lives in crate-private functions, and that is exactly what an
//! assistant working on the code needs to find.
//!
//! Usage:
//!
//! ```text
//! cargo run --manifest-path tools/rustdoc-gen/Cargo.toml -- [repo-root]
//! just gen-llm-docs
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use syn::{parse_quote, Attribute, Expr, ImplItem, Item, Lit, Meta, TraitItem, Type, Visibility};

/// A crate whose sources are documented.
struct Crate {
    /// Crate directory relative to the repository root.
    dir: &'static str,
    /// Source roots relative to `dir`, walked recursively.
    roots: &'static [&'static str],
}

/// A group of crates written to a single output file.
struct Group {
    title: &'static str,
    output: &'static str,
    crates: &'static [Crate],
}

const GROUPS: &[Group] = &[
    Group {
        title: "Driver",
        output: "docs/LLMs/RUSTDOC-driver.md",
        crates: &[
            Crate { dir: "driver", roots: &["src"] },
            Crate { dir: "driver/kernel", roots: &["src"] },
        ],
    },
    Group {
        title: "Protocol",
        output: "docs/LLMs/RUSTDOC-protocol.md",
        crates: &[Crate { dir: "protocol", roots: &["src"] }],
    },
    Group {
        title: "WDK Bindings",
        output: "docs/LLMs/RUSTDOC-wdk.md",
        crates: &[Crate { dir: "wdk", roots: &["src"] }],
    },
    Group {
        // mock/driver has no sources of its own: it compiles driver/src.
        title: "Mock driver (host mock WDK, harness, zfsim extension)",
        output: "docs/LLMs/RUSTDOC-mock.md",
        crates: &[
            Crate { dir: "mock/wdk", roots: &["src"] },
            Crate { dir: "mock/harness", roots: &["src"] },
            Crate { dir: "mock/sim", roots: &["src"] },
        ],
    },
    Group {
        title: "Release Tools",
        output: "docs/LLMs/RUSTDOC-tools.md",
        crates: &[Crate { dir: "release", roots: &["src"] }],
    },
];

fn main() {
    let root = std::env::args().nth(1).unwrap_or_else(|| ".".into());
    let root = fs::canonicalize(&root).unwrap_or_else(|e| fatal(&format!("resolving {root}: {e}")));

    for group in GROUPS {
        let mut out = String::new();
        writeln!(out, "# ZenithFence — Rust Item Reference: {}\n", group.title).unwrap();
        out.push_str("> Auto-generated by `cargo run --manifest-path tools/rustdoc-gen/Cargo.toml -- .` (`just gen-llm-docs`) — do not edit by hand.  \n");
        out.push_str("> One section per source file: module docs, constants, macros, full type definitions, impl blocks, functions and extern blocks.  \n");
        out.push_str("> Includes private items. Function bodies, long initializers and test code are stripped.\n\n---\n\n");

        let mut files = 0;
        for krate in group.crates {
            for src_root in krate.roots {
                let mut paths = Vec::new();
                collect_rs(&root.join(krate.dir).join(src_root), &mut paths);
                paths.sort();
                for path in paths {
                    let rel = path.strip_prefix(&root).unwrap().to_string_lossy().replace('\\', "/");
                    document_file(&mut out, &path, &rel);
                    files += 1;
                }
            }
        }

        let out_path = root.join(group.output);
        fs::create_dir_all(out_path.parent().unwrap()).unwrap();
        fs::write(&out_path, out).unwrap_or_else(|e| fatal(&format!("writing {}: {e}", group.output)));
        eprintln!("wrote {} ({files} files)", group.output);
    }
}

/// Recursively collects `.rs` files under `dir`.
fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_dir() {
            if !name.starts_with('.') && name != "target" {
                collect_rs(&path, out);
            }
        } else if name.ends_with(".rs") {
            out.push(path);
        }
    }
}

/// Writes the section(s) for one source file.
fn document_file(out: &mut String, path: &Path, rel: &str) {
    let source = match fs::read_to_string(path) {
        Ok(s) => s,
        Err(e) => fatal(&format!("reading {rel}: {e}")),
    };
    match syn::parse_file(&source) {
        Ok(file) => document_items(out, &format!("`{rel}`"), &docs_of(&file.attrs), &file.items),
        Err(e) => {
            writeln!(out, "## `{rel}`\n\n_Could not be parsed: {e}_\n\n---\n").unwrap();
        }
    }
}

/// Writes one Markdown section for a module's items, then one section per
/// inline (non-test) submodule.
fn document_items(out: &mut String, heading: &str, module_docs: &str, items: &[Item]) {
    let mut reexports = Vec::new();
    let mut consts = Vec::new();
    let mut macros = Vec::new();
    let mut types: Vec<(String, String, String)> = Vec::new(); // (name, docs, code)
    let mut inherent: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new(); // type -> [(docs, code)]
    let mut trait_impls = Vec::new();
    let mut funcs = Vec::new();
    let mut externs = Vec::new();
    let mut submodules = Vec::new();

    for item in items {
        if is_test(item_attrs(item)) {
            continue;
        }
        match item {
            Item::Use(u) if !matches!(u.vis, Visibility::Inherited) => {
                let mut u = u.clone();
                clean_attrs(&mut u.attrs, false);
                reexports.push(render(Item::Use(u)));
            }
            Item::Const(_) | Item::Static(_) => consts.push((docs_of(item_attrs(item)), render_value(item))),
            Item::Macro(m) => {
                if let Some(ident) = &m.ident {
                    macros.push((docs_of(&m.attrs), format!("macro_rules! {ident} {{ /* ... */ }}")));
                }
            }
            Item::Struct(_) | Item::Enum(_) | Item::Union(_) | Item::Type(_) | Item::Trait(_) | Item::TraitAlias(_) => {
                types.push((item_name(item), docs_of(item_attrs(item)), render_type(item)));
            }
            Item::Impl(imp) if imp.trait_.is_some() => trait_impls.push(render_trait_impl(imp)),
            Item::Impl(imp) => {
                if let Some(code) = render_inherent_impl(imp) {
                    inherent.entry(type_name(&imp.self_ty)).or_default().push((docs_of(&imp.attrs), code));
                }
            }
            Item::Fn(f) => {
                let mut f = f.clone();
                clean_attrs(&mut f.attrs, false);
                f.block = Box::new(parse_quote!({}));
                funcs.push((docs_of(item_attrs(item)), strip_bodies(&render(Item::Fn(f)))));
            }
            Item::ForeignMod(fm) => {
                let mut fm = fm.clone();
                clean_attrs(&mut fm.attrs, false);
                for fi in &mut fm.items {
                    if let syn::ForeignItem::Fn(f) = fi {
                        clean_attrs(&mut f.attrs, true);
                    } else if let syn::ForeignItem::Static(s) = fi {
                        clean_attrs(&mut s.attrs, true);
                    }
                }
                externs.push((docs_of(&fm.attrs), render(Item::ForeignMod(fm))));
            }
            Item::Mod(m) => {
                if let Some((_, sub)) = &m.content {
                    submodules.push((format!("{heading} — `mod {}`", m.ident), docs_of(&m.attrs), sub.clone()));
                }
            }
            _ => {}
        }
    }

    let empty = reexports.is_empty()
        && consts.is_empty()
        && macros.is_empty()
        && types.is_empty()
        && inherent.is_empty()
        && trait_impls.is_empty()
        && funcs.is_empty()
        && externs.is_empty();
    if !(empty && module_docs.is_empty()) {
        writeln!(out, "## {heading}\n").unwrap();
        if !module_docs.is_empty() {
            writeln!(out, "{module_docs}\n").unwrap();
        }
        if !reexports.is_empty() {
            out.push_str("### Re-exports\n\n");
            code_block(out, &reexports.concat());
        }
        if !consts.is_empty() {
            out.push_str("### Constants & statics\n\n");
            documented_blocks(out, &consts);
        }
        if !macros.is_empty() {
            out.push_str("### Macros\n\n");
            documented_blocks(out, &macros);
        }
        if !types.is_empty() {
            out.push_str("### Types\n\n");
            for (name, docs, code) in &types {
                writeln!(out, "#### `{name}`\n").unwrap();
                prose(out, docs);
                code_block(out, code);
                if let Some(impls) = inherent.remove(name) {
                    documented_blocks(out, &impls);
                }
            }
        }
        if !inherent.is_empty() {
            out.push_str("### Impl blocks (types defined elsewhere)\n\n");
            for (name, impls) in &inherent {
                writeln!(out, "#### `{name}`\n").unwrap();
                documented_blocks(out, impls);
            }
        }
        if !trait_impls.is_empty() {
            out.push_str("### Trait implementations\n\n");
            code_block(out, &trait_impls.join("\n"));
        }
        if !funcs.is_empty() {
            out.push_str("### Functions\n\n");
            documented_blocks(out, &funcs);
        }
        if !externs.is_empty() {
            out.push_str("### Extern blocks\n\n");
            documented_blocks(out, &externs);
        }
        out.push_str("---\n\n");
    }

    for (heading, docs, items) in submodules {
        document_items(out, &heading, &docs, &items);
    }
}

fn prose(out: &mut String, docs: &str) {
    if !docs.is_empty() {
        writeln!(out, "{docs}\n").unwrap();
    }
}

fn code_block(out: &mut String, code: &str) {
    writeln!(out, "```rust\n{}\n```\n", code.trim_end()).unwrap();
}

fn documented_blocks(out: &mut String, entries: &[(String, String)]) {
    for (docs, code) in entries {
        prose(out, docs);
        code_block(out, code);
    }
}

/// Renders a single item as formatted Rust source.
fn render(item: Item) -> String {
    prettyplease::unparse(&syn::File { shebang: None, attrs: Vec::new(), items: vec![item] })
}

/// Renders a const/static, eliding the initializer when it does not fit on one short line.
fn render_value(item: &Item) -> String {
    let mut item = item.clone();
    match &mut item {
        Item::Const(c) => clean_attrs(&mut c.attrs, false),
        Item::Static(s) => clean_attrs(&mut s.attrs, false),
        _ => unreachable!(),
    }
    let full = render(item.clone());
    if full.trim_end().lines().count() == 1 && full.len() <= 120 {
        return full;
    }
    let placeholder: Expr = parse_quote!(__ELIDED__);
    match &mut item {
        Item::Const(c) => c.expr = Box::new(placeholder),
        Item::Static(s) => s.expr = Box::new(placeholder),
        _ => unreachable!(),
    }
    render(item).replace("__ELIDED__", "...")
}

/// Renders a type definition with field/variant docs kept and default trait method bodies removed.
fn render_type(item: &Item) -> String {
    let mut item = item.clone();
    match &mut item {
        Item::Struct(s) => {
            clean_attrs(&mut s.attrs, false);
            s.fields.iter_mut().for_each(|f| clean_attrs(&mut f.attrs, true));
        }
        Item::Enum(e) => {
            clean_attrs(&mut e.attrs, false);
            for v in &mut e.variants {
                clean_attrs(&mut v.attrs, true);
                v.fields.iter_mut().for_each(|f| clean_attrs(&mut f.attrs, true));
            }
        }
        Item::Union(u) => {
            clean_attrs(&mut u.attrs, false);
            u.fields.named.iter_mut().for_each(|f| clean_attrs(&mut f.attrs, true));
        }
        Item::Type(t) => clean_attrs(&mut t.attrs, false),
        Item::TraitAlias(t) => clean_attrs(&mut t.attrs, false),
        Item::Trait(t) => {
            clean_attrs(&mut t.attrs, false);
            for ti in &mut t.items {
                match ti {
                    TraitItem::Fn(f) => {
                        clean_attrs(&mut f.attrs, true);
                        f.default = None;
                    }
                    TraitItem::Const(c) => clean_attrs(&mut c.attrs, true),
                    TraitItem::Type(ty) => clean_attrs(&mut ty.attrs, true),
                    _ => {}
                }
            }
        }
        _ => unreachable!(),
    }
    render(item)
}

/// Renders an inherent impl block with method signatures only. None if it has no items left.
fn render_inherent_impl(imp: &syn::ItemImpl) -> Option<String> {
    let mut imp = imp.clone();
    clean_attrs(&mut imp.attrs, false);
    imp.items.retain(|ii| !is_test(impl_item_attrs(ii)) && !matches!(ii, ImplItem::Macro(_)));
    if imp.items.is_empty() {
        return None;
    }
    for ii in &mut imp.items {
        match ii {
            ImplItem::Fn(f) => {
                clean_attrs(&mut f.attrs, true);
                f.block = parse_quote!({});
            }
            ImplItem::Const(c) => clean_attrs(&mut c.attrs, true),
            ImplItem::Type(t) => clean_attrs(&mut t.attrs, true),
            _ => {}
        }
    }
    Some(strip_bodies(&render(Item::Impl(imp))))
}

/// Renders a trait impl as a one-line header, e.g. `unsafe impl Sync for Foo;`.
fn render_trait_impl(imp: &syn::ItemImpl) -> String {
    let mut imp = imp.clone();
    clean_attrs(&mut imp.attrs, false);
    imp.items.clear();
    let s = strip_bodies(&render(Item::Impl(imp)));
    s.trim_end().trim_end_matches(';').to_string() + "\n"
}

/// Replaces the empty `{}` bodies left after stripping with `;`.
fn strip_bodies(code: &str) -> String {
    let mut lines: Vec<String> = Vec::new();
    for line in code.lines() {
        if line.trim() == "{}" {
            if let Some(prev) = lines.last_mut() {
                prev.push(';');
                continue;
            }
        }
        match line.strip_suffix(" {}") {
            Some(head) => lines.push(format!("{head};")),
            None => lines.push(line.to_string()),
        }
    }
    lines.join("\n") + "\n"
}

/// Extracts the `///` / `//!` doc comment text from attributes.
fn docs_of(attrs: &[Attribute]) -> String {
    let mut lines = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        if let Meta::NameValue(nv) = &attr.meta {
            if let Expr::Lit(lit) = &nv.value {
                if let Lit::Str(s) = &lit.lit {
                    let v = s.value();
                    for line in v.lines() {
                        lines.push(line.strip_prefix(' ').unwrap_or(line).trim_end().to_string());
                    }
                }
            }
        }
    }
    lines.join("\n").trim().to_string()
}

/// Drops attributes that are noise for a reader, optionally keeping doc comments.
fn clean_attrs(attrs: &mut Vec<Attribute>, keep_docs: bool) {
    const KEEP: &[&str] = &["derive", "repr", "cfg", "no_mangle", "export_name", "link", "unsafe"];
    attrs.retain(|a| {
        let p = a.path();
        (keep_docs && p.is_ident("doc")) || KEEP.iter().any(|k| p.is_ident(k))
    });
}

/// True for `#[test]` items and `#[cfg(test)]` items/modules.
fn is_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("test")
            || (a.path().is_ident("cfg")
                && matches!(&a.meta, Meta::List(l) if l.tokens.to_string().trim() == "test"))
    })
}

fn item_attrs(item: &Item) -> &[Attribute] {
    match item {
        Item::Const(i) => &i.attrs,
        Item::Enum(i) => &i.attrs,
        Item::ExternCrate(i) => &i.attrs,
        Item::Fn(i) => &i.attrs,
        Item::ForeignMod(i) => &i.attrs,
        Item::Impl(i) => &i.attrs,
        Item::Macro(i) => &i.attrs,
        Item::Mod(i) => &i.attrs,
        Item::Static(i) => &i.attrs,
        Item::Struct(i) => &i.attrs,
        Item::Trait(i) => &i.attrs,
        Item::TraitAlias(i) => &i.attrs,
        Item::Type(i) => &i.attrs,
        Item::Union(i) => &i.attrs,
        Item::Use(i) => &i.attrs,
        _ => &[],
    }
}

fn impl_item_attrs(item: &ImplItem) -> &[Attribute] {
    match item {
        ImplItem::Const(i) => &i.attrs,
        ImplItem::Fn(i) => &i.attrs,
        ImplItem::Type(i) => &i.attrs,
        ImplItem::Macro(i) => &i.attrs,
        _ => &[],
    }
}

fn item_name(item: &Item) -> String {
    match item {
        Item::Struct(i) => i.ident.to_string(),
        Item::Enum(i) => i.ident.to_string(),
        Item::Union(i) => i.ident.to_string(),
        Item::Type(i) => i.ident.to_string(),
        Item::Trait(i) => i.ident.to_string(),
        Item::TraitAlias(i) => i.ident.to_string(),
        _ => unreachable!(),
    }
}

/// The last path segment of an impl's self type, used to attach impls to their type.
fn type_name(ty: &Type) -> String {
    match ty {
        Type::Path(p) => p.path.segments.last().map(|s| s.ident.to_string()).unwrap_or_default(),
        other => quote::quote!(#other).to_string(),
    }
}

fn fatal(msg: &str) -> ! {
    eprintln!("rustdoc-gen: {msg}");
    std::process::exit(1)
}
