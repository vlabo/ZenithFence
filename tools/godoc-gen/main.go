// Command godoc-gen generates docs/LLMs/GODOC.md, a Markdown reference of the
// Go user-space code (kext_interface, kext_tester) optimized for LLM
// consumption. It walks the repository, parses every non-generated Go package,
// and writes its exported symbols (variables, constants, types, and function
// signatures) together with their doc comments. For `package main` packages,
// which export nothing, all declarations are included instead.
//
// Usage:
//
//	go run ./tools/godoc-gen [repo-root]
//	just gen-llm-docs
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// outputFile is the output path relative to the repository root.
const outputFile = "docs/LLMs/GODOC.md"

// skipDirs lists directory names that are skipped during the directory walk.
// These are either non-Go projects, build output, or the doc tools themselves.
var skipDirs = map[string]bool{
	"vendor":   true,
	"testdata": true,
	"target":   true,
	"tools":    true,
	"libs":     true,
	"npcap":    true,
	"release":  true,
}

func main() {
	// Resolve the repository root from the optional first argument.
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	absRoot, err := filepath.Abs(root)
	if err != nil {
		fatalf("resolving root path: %v", err)
	}

	// Walk the directory tree and collect package documentation.
	var pkgs []packageInfo
	err = filepath.WalkDir(absRoot, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}

		// Skip hidden directories and known non-Go directories.
		if path != absRoot && (strings.HasPrefix(d.Name(), ".") || skipDirs[d.Name()]) {
			return filepath.SkipDir
		}

		// Parse the Go package at this directory, if any.
		info, ok := parsePackageDir(path)
		if ok {
			pkgs = append(pkgs, info)
		}
		return nil
	})
	if err != nil {
		fatalf("walking directory tree: %v", err)
	}

	// Sort packages by import path for deterministic, readable output.
	sort.Slice(pkgs, func(i, j int) bool {
		return pkgs[i].importPath < pkgs[j].importPath
	})

	outPath := filepath.Join(absRoot, outputFile)
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fatalf("creating output directory: %v", err)
	}
	written, skipped, err := writeFile(outPath, pkgs)
	if err != nil {
		fatalf("writing %s: %v", outputFile, err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d packages, %d skipped)\n", outPath, written, skipped)
}

// writeFile writes all packages in pkgs to outPath.
// Returns the number of packages written and skipped (no documented content).
func writeFile(outPath string, pkgs []packageInfo) (written, skipped int, err error) {
	var relevant []packageInfo
	for _, pkg := range pkgs {
		if packageHasContent(pkg.pkg) {
			relevant = append(relevant, pkg)
		} else {
			skipped++
		}
	}

	f, err := os.Create(outPath)
	if err != nil {
		return 0, skipped, err
	}
	defer f.Close()

	// Write the file header.
	fmt.Fprintln(f, "# ZenithFence — Go Package Reference")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "> Auto-generated by `go run ./tools/godoc-gen .` (`just gen-llm-docs`) — do not edit by hand.  ")
	fmt.Fprintln(f, "> Excludes generated files (`Code generated` header), test files, and non-Go directories.  ")
	fmt.Fprintln(f, "> Library packages: exported symbols only. `package main`: all declarations. Function bodies are stripped.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "---")
	fmt.Fprintln(f)

	// Write one section per package.
	for _, pkg := range relevant {
		writePackage(f, pkg)
	}

	return len(relevant), skipped, nil
}

// packageInfo holds the parsed documentation for a single Go package.
type packageInfo struct {
	importPath string
	dir        string
	fset       *token.FileSet
	pkg        *doc.Package
}

// moduleLine matches the module directive of a go.mod file.
var moduleLine = regexp.MustCompile(`(?m)^module\s+(\S+)`)

// importPathFor returns the import path of dir by locating the nearest go.mod
// at or above it. Returns false when dir is not inside a Go module.
func importPathFor(dir string) (string, bool) {
	for modDir := dir; ; modDir = filepath.Dir(modDir) {
		data, err := os.ReadFile(filepath.Join(modDir, "go.mod"))
		if err == nil {
			m := moduleLine.FindSubmatch(data)
			if m == nil {
				return "", false
			}
			rel, err := filepath.Rel(modDir, dir)
			if err != nil {
				return "", false
			}
			if rel == "." {
				return string(m[1]), true
			}
			return string(m[1]) + "/" + filepath.ToSlash(rel), true
		}
		if parent := filepath.Dir(modDir); parent == modDir {
			return "", false
		}
	}
}

// parsePackageDir parses the Go package at dir and returns its documentation.
// Returns (_, false) when the directory has no non-generated, non-test Go files.
func parsePackageDir(dir string) (packageInfo, bool) {
	fset := token.NewFileSet()

	// Parse all Go files in the directory, skipping test files.
	astPkgs, err := parser.ParseDir(fset, dir, func(fi fs.FileInfo) bool { //nolint:staticcheck // parser.ParseDir is deprecated but adequate for this internal doc generator
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil || len(astPkgs) == 0 {
		return packageInfo{}, false
	}

	importPath, ok := importPathFor(dir)
	if !ok {
		return packageInfo{}, false
	}

	// Process each AST package found in the directory (normally just one).
	for _, astPkg := range astPkgs {
		// Skip the test-only package variant (e.g., package foo_test).
		if strings.HasSuffix(astPkg.Name, "_test") {
			continue
		}

		// Remove files that were auto-generated — they add noise without insight.
		dropGeneratedFiles(astPkg)
		if len(astPkg.Files) == 0 {
			continue
		}

		// Exported symbols only, except for main packages which export nothing.
		var mode doc.Mode
		if astPkg.Name == "main" {
			mode = doc.AllDecls
		}
		dpkg := doc.New(astPkg, importPath, mode)
		return packageInfo{importPath: importPath, dir: dir, fset: fset, pkg: dpkg}, true
	}

	return packageInfo{}, false
}

// dropGeneratedFiles removes any file whose comments contain "Code generated"
// from the AST package.
func dropGeneratedFiles(pkg *ast.Package) { //nolint:staticcheck // ast.Package is deprecated but adequate for this internal doc generator
outer:
	for name, f := range pkg.Files {
		for _, cg := range f.Comments {
			for _, c := range cg.List {
				if strings.Contains(c.Text, "Code generated") {
					delete(pkg.Files, name)
					continue outer
				}
			}
		}
	}
}

// writePackage writes the full Markdown section for one package.
func writePackage(w io.Writer, info packageInfo) {
	dp := info.pkg
	fset := info.fset

	// Package heading, source files, and package-level doc comment.
	fmt.Fprintf(w, "## `%s`\n\n", info.importPath)
	fmt.Fprintf(w, "Files: %s\n\n", sourceFiles(fset, info.dir))
	if dp.Doc != "" {
		fmt.Fprintf(w, "%s\n\n", strings.TrimSpace(dp.Doc))
	}

	// Variables — package-level var declarations.
	if len(dp.Vars) > 0 {
		fmt.Fprintln(w, "### Variables")
		fmt.Fprintln(w)
		for _, v := range dp.Vars {
			writeDecl(w, fset, v.Doc, v.Decl)
		}
	}

	// Constants — package-level const declarations.
	if len(dp.Consts) > 0 {
		fmt.Fprintln(w, "### Constants")
		fmt.Fprintln(w)
		for _, c := range dp.Consts {
			writeDecl(w, fset, c.Doc, c.Decl)
		}
	}

	// Types — structs, interfaces, and type aliases, with methods grouped under them.
	if len(dp.Types) > 0 {
		fmt.Fprintln(w, "### Types")
		fmt.Fprintln(w)
		for _, t := range dp.Types {
			writeType(w, fset, t)
		}
	}

	// Functions — top-level functions not associated with any type.
	if len(dp.Funcs) > 0 {
		fmt.Fprintln(w, "### Functions")
		fmt.Fprintln(w)
		for _, fn := range dp.Funcs {
			writeFunc(w, fset, fn)
		}
	}

	fmt.Fprintln(w, "---")
	fmt.Fprintln(w)
}

// sourceFiles lists the repo-relative files of the package, so the reader can
// jump from a symbol to its source.
func sourceFiles(fset *token.FileSet, dir string) string {
	var names []string
	fset.Iterate(func(f *token.File) bool {
		if filepath.Dir(f.Name()) == dir {
			names = append(names, "`"+filepath.Base(f.Name())+"`")
		}
		return true
	})
	sort.Strings(names)
	return strings.Join(names, ", ")
}

// writeDecl writes a var or const declaration block with its doc comment.
func writeDecl(w io.Writer, fset *token.FileSet, docText string, decl *ast.GenDecl) {
	if docText != "" {
		fmt.Fprintf(w, "%s\n\n", strings.TrimSpace(docText))
	}
	fmt.Fprintln(w, "```go")
	fmt.Fprintln(w, strings.TrimRight(formatNode(fset, decl), "\n"))
	fmt.Fprintln(w, "```")
	fmt.Fprintln(w)
}

// writeType writes a type declaration, its constructor functions, and its methods.
func writeType(w io.Writer, fset *token.FileSet, t *doc.Type) {
	fmt.Fprintf(w, "#### `%s`\n\n", t.Name)
	if t.Doc != "" {
		fmt.Fprintf(w, "%s\n\n", strings.TrimSpace(t.Doc))
	}

	fmt.Fprintln(w, "```go")
	fmt.Fprintln(w, strings.TrimRight(formatNode(fset, t.Decl), "\n"))
	fmt.Fprintln(w, "```")
	fmt.Fprintln(w)

	// Constants and variables of this type (e.g. enum-like iota blocks).
	for _, c := range t.Consts {
		writeDecl(w, fset, c.Doc, c.Decl)
	}
	for _, v := range t.Vars {
		writeDecl(w, fset, v.Doc, v.Decl)
	}

	// Constructor functions and other funcs that return this type.
	for _, fn := range t.Funcs {
		writeFunc(w, fset, fn)
	}

	// Methods on this type (and its pointer receiver).
	for _, fn := range t.Methods {
		writeFunc(w, fset, fn)
	}
}

// writeFunc writes a function or method signature and its doc comment.
func writeFunc(w io.Writer, fset *token.FileSet, fn *doc.Func) {
	if fn.Doc != "" {
		fmt.Fprintf(w, "%s\n\n", strings.TrimSpace(fn.Doc))
	}
	fmt.Fprintln(w, "```go")
	fmt.Fprintln(w, strings.TrimRight(formatFuncSig(fset, fn.Decl), "\n"))
	fmt.Fprintln(w, "```")
	fmt.Fprintln(w)
}

// formatNode formats an AST node as canonical Go source using go/format.
func formatNode(fset *token.FileSet, node any) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, fset, node); err != nil {
		return fmt.Sprintf("/* format error: %v */", err)
	}
	return buf.String()
}

// formatFuncSig formats a function declaration as its signature only, without
// the body.
func formatFuncSig(fset *token.FileSet, fn *ast.FuncDecl) string {
	sig := &ast.FuncDecl{
		Recv: fn.Recv,
		Name: fn.Name,
		Type: fn.Type,
	}
	return formatNode(fset, sig)
}

// packageHasContent reports whether a package has anything worth writing.
func packageHasContent(dp *doc.Package) bool {
	return dp.Doc != "" || len(dp.Vars) > 0 || len(dp.Consts) > 0 ||
		len(dp.Types) > 0 || len(dp.Funcs) > 0
}

// fatalf prints an error message to stderr and exits with status 1.
func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "godoc-gen: "+format+"\n", args...)
	os.Exit(1)
}
